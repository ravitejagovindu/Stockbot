"""
FInsight Trading Engine — Live Deployment Authorization Script

Run this ONCE after a successful Pass 2 backtest to authorize live trading.

Usage:
    python authorize_live.py --confirm-ledger=backtest/outputs/audit.json

This script:
1. Reads and validates audit.json (dual gate must pass)
2. Verifies a clean git working tree
3. Captures the current HEAD SHA
4. Writes authorized_deployment.json
5. Commits authorized_deployment.json to Git

After running this, the live EOD runner is permitted to execute.
Any code change after this will break the SHA lock and require re-authorization.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime
from pathlib import Path

BASE_DIR = Path(__file__).parent
AUTHORIZED_FILE = BASE_DIR / "authorized_deployment.json"


def run_git(args: list[str]) -> str:
    """Run git command, return stdout. Exits on failure."""
    result = subprocess.run(
        ["git"] + args,
        capture_output=True,
        text=True,
        cwd=BASE_DIR,
    )
    if result.returncode != 0:
        print(f"[ERROR] git {' '.join(args)} failed:\n{result.stderr}")
        sys.exit(1)
    return result.stdout.strip()


def validate_audit(audit_path: Path) -> dict:
    """Load and validate audit.json. Returns audit dict if valid."""
    if not audit_path.exists():
        print(f"[ERROR] audit.json not found at: {audit_path}")
        print("  → Run the Pass 2 backtest first: python backtest/pass2_compliant_run.py")
        sys.exit(1)

    with open(audit_path, "r", encoding="utf-8") as f:
        audit = json.load(f)

    print("\n── Audit Ledger Validation ─────────────────────────────────────")

    dual_gate = audit.get("dual_gate", {})

    # Check max drawdown
    dd_pass = dual_gate.get("max_drawdown_pass", False)
    print(f"  Max Drawdown < 15%:          {'✓ PASS' if dd_pass else '✗ FAIL'}")

    # Check outperformance
    op_pass = dual_gate.get("outperformance_pass", False)
    print(f"  Outperforms Nifty 50:        {'✓ PASS' if op_pass else '✗ FAIL'}")

    # Overall eligibility
    eligible = audit.get("eligible_for_deployment", False)
    print(f"  Eligible for Deployment:     {'✓ YES' if eligible else '✗ NO'}")
    print()

    # Print per-regime summary
    for regime_name, stats in audit.get("regimes", {}).items():
        print(f"  Regime [{regime_name}]:")
        print(f"    Max Drawdown:   {stats.get('max_drawdown_pct', 'N/A'):.1f}%")
        print(f"    CAGR:           {stats.get('cagr_pct', 'N/A'):.1f}%")
        print(f"    Nifty CAGR:     {stats.get('nifty_cagr_pct', 'N/A'):.1f}%")
        print(f"    Alpha:          {stats.get('alpha_pct', 'N/A'):.1f}%")
        print(f"    Sharpe:         {stats.get('sharpe', 'N/A'):.2f}")
        print(f"    Total Trades:   {stats.get('total_trades', 'N/A')}")
        print()

    if not eligible:
        print("[ERROR] Strategy does NOT meet the Dual Gate deployment criteria.")
        print("  → The engine is NOT authorized for live capital deployment.")
        sys.exit(1)

    print("[OK] Dual Gate passed. Proceeding with authorization...")
    return audit


def check_clean_tree() -> None:
    """Ensure git working tree is clean. Exits if dirty."""
    status = run_git(["status", "--porcelain"])
    if status:
        print("[ERROR] Git working tree has uncommitted changes:")
        print(status)
        print("\n  → Commit or stash all changes before authorizing.")
        sys.exit(1)
    print("[OK] Working tree is clean.")


def main():
    parser = argparse.ArgumentParser(
        description="Authorize FInsight for live trading after passing the backtest Dual Gate."
    )
    parser.add_argument(
        "--confirm-ledger",
        required=True,
        metavar="PATH",
        help="Path to the audit.json generated by Pass 2 backtest.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Validate only — do not write authorized_deployment.json or commit.",
    )
    args = parser.parse_args()

    audit_path = Path(args.confirm_ledger)

    print("\n╔══════════════════════════════════════════════════════════════╗")
    print("║     FInsight Trading Engine — Live Deployment Authorization    ║")
    print("╚══════════════════════════════════════════════════════════════╝\n")

    # Step 1: Validate audit.json
    audit = validate_audit(audit_path)

    # Step 2: Check clean working tree
    check_clean_tree()

    # Step 3: Get current HEAD SHA
    sha = run_git(["rev-parse", "HEAD"])
    short_sha = sha[:8]
    print(f"[OK] Current HEAD SHA: {sha}")

    if args.dry_run:
        print("\n[DRY RUN] Validation passed. No files written (--dry-run mode).")
        sys.exit(0)

    # Step 4: Write authorized_deployment.json
    deployment_info = {
        "authorized_at": datetime.now().isoformat(),
        "authorized_sha": sha,
        "dual_gate_summary": audit.get("dual_gate", {}),
        "strategy_config_sha": audit.get("strategy_config_sha", "unknown"),
        "audit_generated_at": audit.get("generated_at", "unknown"),
        "note": (
            "This file authorizes the live EOD runner. "
            "Any code change after this will break the SHA lock. "
            "Re-run authorize_live.py after any change."
        ),
    }

    with open(AUTHORIZED_FILE, "w", encoding="utf-8") as f:
        json.dump(deployment_info, f, indent=2)

    print(f"[OK] authorized_deployment.json written.")

    # Step 5: Stage and commit
    run_git(["add", "authorized_deployment.json"])
    run_git(["commit", "-m", f"chore: authorize live deployment [{short_sha}]"])

    print(f"\n╔══════════════════════════════════════════════════════════════╗")
    print(f"║  ✓  AUTHORIZATION COMPLETE                                    ║")
    print(f"║     SHA: {sha[:8]}                                            ║")
    print(f"╚══════════════════════════════════════════════════════════════╝\n")
    print("The live EOD runner is now authorized. Start it with:")
    print("    python -m live_runner.main")
    print("\nWARNING: Any code change will break the lock. Re-authorize after each change.")


if __name__ == "__main__":
    main()
