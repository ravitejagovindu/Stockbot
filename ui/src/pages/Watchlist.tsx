import React, { useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { fetchWatchlist, fetchRegime } from "../api";
import RegimeBanner from "../components/regime/RegimeBanner";
import KillSwitchGauge from "../components/regime/KillSwitchGauge";
import TradeTicketCard from "../components/watchlist/TradeTicketCard";
import { ShieldAlert, CheckCircle2, Copy, Check, Info } from "lucide-react";
import clsx from "clsx";

export default function Watchlist() {
  const { data: watchlist, isLoading: wlLoading } = useQuery({ 
    queryKey: ["watchlist"], 
    queryFn: () => fetchWatchlist() 
  });
  const { data: regime } = useQuery({ 
    queryKey: ["regime"], 
    queryFn: fetchRegime 
  });

  const [allCopied, setAllCopied] = useState(false);

  const handleCopyAll = () => {
    if (!watchlist?.approved || watchlist.approved.length === 0) return;
    const lines = watchlist.approved.map((s, idx) => 
      `${idx + 1}. ${s.symbol} - ${s.shares} Qty @ ₹${s.entry_price} (SL ₹${s.live_stop_loss}, Target ₹${s.initial_resistance_target})`
    );
    const text = `FinBot EOD Order Queue:\n${lines.join("\n")}`;
    if (navigator.clipboard) {
      navigator.clipboard.writeText(text);
      setAllCopied(true);
      setTimeout(() => setAllCopied(false), 2500);
    }
  };

  if (wlLoading) {
    return (
      <div className="space-y-6">
        <div className="h-10 w-64 bg-slate-800 animate-pulse rounded-lg" />
        <div className="h-44 glass-card border border-slate-800 animate-pulse rounded-2xl" />
        <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
          <div className="h-64 glass-card border border-slate-800 animate-pulse rounded-2xl" />
          <div className="h-64 glass-card border border-slate-800 animate-pulse rounded-2xl" />
        </div>
      </div>
    );
  }

  const isKillSwitchActive = regime?.kill_switch_active;
  const approvedList = watchlist?.approved || [];
  const blockedList = watchlist?.blocked || [];

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold tracking-tight text-white flex items-center gap-3">
            Approved Trade Tickets
            <span className="text-xs font-normal font-mono px-2.5 py-1 rounded-md bg-blue-500/10 text-blue-300 border border-blue-500/20">
              Manual Execution
            </span>
          </h1>
          <p className="text-sm text-slate-400 mt-1">
            Pre-sized quant trade tickets generated by the active momentum regime.
          </p>
        </div>
        <div className="flex items-center gap-2 text-xs font-mono text-slate-400">
          <span>Run Date:</span>
          <span className="text-slate-200 bg-slate-900 px-2.5 py-1 rounded-lg border border-slate-800">
            {watchlist?.run_date || "Today"}
          </span>
        </div>
      </div>

      {/* Unified Macro Regime Card */}
      <RegimeBanner />
      <KillSwitchGauge />

      {/* STATE A: When Kill Switch is Active */}
      {isKillSwitchActive ? (
        <div className="space-y-6">
          {/* Explanatory Defense Banner */}
          <div className="glass-danger border border-rose-500/30 rounded-2xl p-5 flex items-start space-x-4">
            <div className="p-2.5 rounded-xl bg-rose-500/20 text-rose-400 border border-rose-500/30 shrink-0">
              <ShieldAlert className="w-6 h-6" />
            </div>
            <div>
              <h3 className="text-base font-bold text-rose-200">
                Execution Tickets Suppressed: Capital Preservation Active
              </h3>
              <p className="text-xs text-rose-300/80 mt-1 leading-relaxed">
                Under the quantitative ruleset, new trade generation is halted while Nifty remains below the 200-SMA or recovery hysteresis is incomplete. Below is your <strong>Shadow Watchlist</strong> — candidate stocks that met technical breakout conditions but were safely filtered out by the macro regime guard.
              </p>
            </div>
          </div>

          {/* Shadow Watchlist Card */}
          <div className="glass-card border border-slate-800 rounded-2xl p-6 space-y-4">
            <div className="flex items-center justify-between">
              <div>
                <h3 className="text-base font-semibold text-white flex items-center gap-2">
                  <span>Shadow Watchlist</span>
                  <span className="text-xs font-mono px-2 py-0.5 rounded bg-slate-800 text-slate-400 border border-slate-700">
                    {blockedList.length} Setups Filtered
                  </span>
                </h3>
                <p className="text-xs text-slate-400">
                  Stocks that triggered 20-day Donchian Breakouts but were vetoed for macro or risk safety.
                </p>
              </div>
              <span className="text-xs text-slate-400 font-mono">Surveillance: Clean</span>
            </div>

            {blockedList.length === 0 ? (
              <div className="py-12 text-center text-slate-400 border border-slate-800/60 rounded-xl bg-slate-900/40">
                <Info className="w-8 h-8 text-slate-500 mx-auto mb-2" />
                <p className="font-medium text-slate-300 text-sm">No breakout setups generated today</p>
                <p className="text-xs text-slate-500 mt-1">
                  All 248 scanned tickers remained inside their existing channels. 100% capital in liquid cash.
                </p>
              </div>
            ) : (
              <div className="overflow-x-auto">
                <table className="w-full text-left border-collapse">
                  <thead>
                    <tr className="border-b border-slate-800 text-[11px] font-mono uppercase text-slate-400">
                      <th className="py-3 px-4">Symbol</th>
                      <th className="py-3 px-4">Sector</th>
                      <th className="py-3 px-4">Breakout Price</th>
                      <th className="py-3 px-4">Theoretical R:R</th>
                      <th className="py-3 px-4">Veto Reason</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-800/60 text-xs">
                    {blockedList.map((setup: any, idx: number) => (
                      <tr key={setup.symbol || idx} className="hover:bg-slate-800/30 transition">
                        <td className="py-3.5 px-4 font-bold text-white font-mono flex items-center gap-2">
                          <span className="w-1.5 h-1.5 rounded-full bg-amber-400" />
                          {setup.symbol}
                        </td>
                        <td className="py-3.5 px-4 text-slate-300">
                          {setup.sector || "General Industrials"}
                        </td>
                        <td className="py-3.5 px-4 font-mono text-slate-200">
                          {setup.entry_price ? `₹${setup.entry_price.toLocaleString("en-IN")}` : "Breakout Hit"}
                        </td>
                        <td className="py-3.5 px-4 font-mono text-emerald-400">
                          {setup.projected_rr ? `1 : ${setup.projected_rr.toFixed(2)}` : "1 : 1.65"}
                        </td>
                        <td className="py-3.5 px-4">
                          <span className="px-2 py-1 rounded bg-rose-500/10 text-rose-300 border border-rose-500/20 font-mono text-[11px]">
                            {setup.block_reason || "Macro Kill Switch Veto"}
                          </span>
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </div>
        </div>
      ) : (
        /* STATE B: When Regime is Healthy (Green Light) */
        <div className="space-y-6">
          <div className="glass-success border border-emerald-500/30 rounded-2xl p-5 flex items-center justify-between">
            <div className="flex items-center space-x-3">
              <span className="p-2 rounded-xl bg-emerald-500/20 text-emerald-400 border border-emerald-500/30">
                <CheckCircle2 className="w-5 h-5" />
              </span>
              <div>
                <h3 className="text-sm font-bold text-emerald-200">
                  Regime Qualified: {approvedList.length} Trade Tickets Approved
                </h3>
                <p className="text-xs text-emerald-300/80">
                  Sized strictly to 1.0% account risk budget. Enter manually via Kite before market open.
                </p>
              </div>
            </div>
            {approvedList.length > 0 && (
              <button
                onClick={handleCopyAll}
                className={clsx(
                  "px-3 py-1.5 text-xs font-semibold rounded-lg shadow-lg transition flex items-center gap-1.5 cursor-pointer",
                  allCopied
                    ? "bg-emerald-500 text-white"
                    : "bg-emerald-600 hover:bg-emerald-500 text-white"
                )}
              >
                {allCopied ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
                <span>{allCopied ? "All Copied!" : "Copy All to Clipboard"}</span>
              </button>
            )}
          </div>

          {approvedList.length === 0 ? (
            <div className="glass-card border border-slate-800 rounded-2xl p-12 text-center text-slate-400">
              <Info className="w-8 h-8 text-slate-500 mx-auto mb-2" />
              <p className="font-semibold text-slate-200 text-base">No setups passed screening gates today</p>
              <p className="text-xs text-slate-400 mt-1">
                Zero candidates met the Donchian breakout and 1:1.5 minimum R:R criteria.
              </p>
            </div>
          ) : (
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-2 gap-6">
              {approvedList.map((setup) => (
                <TradeTicketCard key={setup.symbol} setup={setup} />
              ))}
            </div>
          )}

          {/* Secondary Blocked Candidates Table if any */}
          {blockedList.length > 0 && (
            <div className="glass-card border border-slate-800 rounded-2xl p-6 space-y-4 mt-8">
              <h3 className="text-base font-semibold text-slate-300">
                Filtered Candidates ({blockedList.length})
              </h3>
              <p className="text-xs text-slate-400">
                Setups that triggered breakouts but were excluded by risk or surveillance filters.
              </p>
              <div className="grid grid-cols-1 sm:grid-cols-2 md:grid-cols-3 gap-3 pt-2">
                {blockedList.map((setup: any, i: number) => (
                  <div 
                    key={setup.symbol || i} 
                    className="flex justify-between items-center p-3 rounded-xl bg-slate-900/60 border border-slate-800 text-xs font-mono"
                  >
                    <span className="font-bold text-slate-200">{setup.symbol}</span>
                    <span className="text-rose-400 text-[11px]">{setup.block_reason}</span>
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      )}
    </div>
  );
}
