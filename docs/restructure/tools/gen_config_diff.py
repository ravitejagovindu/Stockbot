"""Generates docs/restructure/CONFIG_DIFF.md: every shared setting, its legacy path/value and its new path/value (acceptance item: values carried over unchanged)."""
import csv
from pathlib import Path

import yaml

from stockbot.config.shared import SHARED_YAML, load_shared_config

ROOT = Path(__file__).resolve().parents[3]
LEG = yaml.safe_load(open(ROOT / "strategy_config.yaml", encoding="utf-8"))
REN = {"portfolio_risk": "risk", "exclusions": "earnings", "live": "trade_management", "validation_gates": "gates"}
rows = ["# Shared config vs strategy_config.yaml (generated by docs/restructure/tools/gen_config_diff.py)", "",
        "`stockbot/config/shared.yaml` carries every value below; the test `tests/unit/test_shared_config.py` asserts equality and type for each row.", "",
        "| new key | legacy key | value | identical |", "|---|---|---|---|"]
same = 0
for k, v in load_shared_config().flat().items():
    s, key = k.split(".", 1)
    ls = REN.get(s, s)
    old = LEG[ls][key]
    ok = (v == [dict(name=w["name"], role=w["role"], start=w["start"], end=w["end"]) for w in old]) if key == "regimes" else (v == old and type(v) is type(old))
    same += ok
    rows.append(f"| `{k}` | `{ls}.{key}` | `{v if key != 'regimes' else '3 windows'}` | {'yes' if ok else '**NO**'} |")
rows += ["", f"{same} of {len(rows) - 6} settings identical.", "", "## Legacy keys NOT carried over (left in strategy_config.yaml until Phase 10)", "", "| legacy key | class | where it goes |", "|---|---|---|"]
for r in csv.DictReader(open(ROOT / "docs/restructure/CONFIG_KEYS.csv", encoding="utf-8", newline="")):
    if not r["class"].startswith("shared"):
        rows.append(f"| `{r['key']}` | {r['class']} | {r['proposed_home']} |")
(ROOT / "docs/restructure/CONFIG_DIFF.md").write_text("\n".join(rows) + "\n", encoding="utf-8")
print(rows[-1] if False else f"{same} identical")
